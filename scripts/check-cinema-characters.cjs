const fs = require('node:fs/promises')
const path = require('node:path')
const assert = require('node:assert/strict')

async function main() {
  const { chromium } = require(process.env.CINEMIND_PLAYWRIGHT_PATH || 'playwright')
  const output = path.resolve('.impeccable/review/characters')
  await fs.mkdir(output, { recursive: true })
  const browser = await chromium.launch({headless:true,args:['--enable-unsafe-swiftshader'],...(process.env.CINEMIND_CHROMIUM_PATH ? {executablePath:process.env.CINEMIND_CHROMIUM_PATH} : {})})
  const errors = [], failures = []
  try {
    for (const [name, viewport] of [['desktop',{width:1440,height:1000}],['mobile',{width:390,height:844}]]) {
      const page = await browser.newPage({viewport,deviceScaleFactor:1,reducedMotion:'reduce'})
      page.on('pageerror',e=>errors.push(e.message))
      page.on('response',response=>{if(response.url().includes('/3d/') && response.status() >= 400) failures.push(response.url())})
      await page.goto(process.env.CINEMIND_CINEMA_URL || 'http://127.0.0.1:3000/watch-party/demo-3d',{waitUntil:'domcontentloaded',timeout:120000})
      await page.getByText('Đã ngồi vào ghế.',{exact:false}).waitFor({timeout:120000})
      await page.waitForTimeout(1200)
      await page.screenshot({path:path.join(output,name+'.png'),fullPage:true})
      await page.getByRole('button',{name:'Nhân vật',exact:true}).click()
      await page.screenshot({path:path.join(output,name+'-regular.png'),fullPage:true})
      await page.getByRole('button',{name:'Nữ thường',exact:true}).click()
      await page.getByRole('button',{name:'Nữ thường',exact:true,pressed:true}).waitFor()
      await page.getByText('Đã ngồi vào ghế.',{exact:false}).waitFor()
      await page.getByRole('button',{name:'VIP',exact:true}).click()
      await page.getByRole('button',{name:'Nữ VIP',exact:true,pressed:true}).waitFor()
      await page.getByRole('button',{name:'Ghế V2, còn trống',exact:true}).click()
      await page.getByRole('button',{name:'Ngồi thử ghế V2',exact:true}).click()
      await page.getByRole('button',{name:'Ghế V2, của bạn',exact:true}).waitFor()
      await page.getByText('Đã ngồi vào ghế.',{exact:false}).waitFor()
      await page.waitForTimeout(500)
      await page.getByRole('heading',{name:'Nhân vật tại ghế V2',exact:true}).scrollIntoViewIfNeeded()
      await page.getByRole('region',{name:'Chọn nhân vật thử nghiệm'}).scrollIntoViewIfNeeded()
      await page.evaluate(()=>window.scrollTo(0,0))
      await page.screenshot({path:path.join(output,name+'-vip.png'),fullPage:true})
      assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth > innerWidth),false,name+' overflow')
      await page.getByRole('button',{name:'Nam VIP',exact:true}).click()
      await page.getByText('Đã ngồi vào ghế.',{exact:false}).waitFor()
      await page.screenshot({path:path.join(output,name+'-male-vip.png'),fullPage:true})
      await page.getByRole('button',{name:'Ghế A1, Minh Anh',exact:true}).click()
      assert.equal(await page.getByRole('button',{name:'Chọn một ghế để tiếp tục',exact:true}).isDisabled(),true)
      await page.reload({waitUntil:'domcontentloaded'})
      await page.getByRole('button',{name:'Nam VIP',exact:true,pressed:true}).waitFor({timeout:60000})
      await page.getByText('Đã ngồi vào ghế.',{exact:false}).waitFor()
      await page.emulateMedia({reducedMotion:'no-preference'})
      assert.equal(await page.getByRole('button',{name:'Đi vào và ngồi lại',exact:true}).count(),0)
      await page.getByRole('button',{name:'Ghế E2, còn trống',exact:true}).click()
      await page.getByRole('button',{name:'Ngồi thử ghế E2',exact:true}).click()
      await page.getByText('Bạn đang đi đến ghế…',{exact:true}).waitFor()
      await page.getByText('Đã ngồi vào ghế.',{exact:false}).waitFor({timeout:30000})
      console.log(name+': four variants, regular/VIP seats, occupied rejection, persistence, reduced motion, animated entry passed')
      await page.close()
    }
    assert.deepEqual(errors,[]);assert.deepEqual(failures,[])
    console.log('No page errors or failed 3D assets. Captures: '+output)
  } finally {await browser.close()}
}
main().catch(e=>{console.error(e);process.exitCode=1})
